"""
SOF regression - Normal scenario
Step 2: fit FunSCOPE-U (unconstrained) and FunSCOPE (beta(t) >= 0) to every simulated sample.

Reads the data generated by 01_generate_data.R and writes in ./output, for each
N and constraint setting:
    X_ScenarioB_N_<N>_m_50_int_constraints_<name>_centered_True_knots_14.txt   metrics
    ... .png / _somebetas.png                                                  plots
    ... .dat                                                                    all results (shelve)
"""

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1]))

from funscope import SOFR_basis
from funscope.experiments import (
    bias_variance,
    data_file,
    mean_std,
    plot_band,
    plot_some,
    read_array,
    read_csv,
    read_grid,
    save_shelf,
    write_report,
)

OUTPUT = HERE / "output"

# =============================================================================
# Settings
# =============================================================================
SCENARIO = "B"
N_VALUES = [25, 50, 100]
M1 = 50
N_SIM = 200

DEGREE = 3
KNOTS = 14
G = 2000           # fine grid used to compute the integrals
CENTERED = True
CONSTRAINTS = {    # name used in the output files -> shape constraints
    "None": None,
    "Zero_Positive": {"X": {0: {"+": 0}}},   # beta(t) >= 0
}
ALPHA_CONSTRAINTS = []
YLIM = (-0.1, 4.5)


# =============================================================================
# Steps
# =============================================================================
def load_data(N):
    X_se = read_array(data_file(OUTPUT, "X", SCENARIO, N, M1))
    y = read_array(data_file(OUTPUT, "Y", SCENARIO, N, M1))
    t = read_grid(data_file(OUTPUT, "T1", SCENARIO, N, M1))
    Beta_real = read_csv(data_file(OUTPUT, "BetaT1", SCENARIO, N, M1))
    return X_se, y, t, Beta_real


def run_simulations(X_se, y, t, Beta_real, N, name, int_constraints):
    """Fit the model to each Monte Carlo sample."""
    keys = ["SOFR", "Delta", "Beta_est", "y_est", "MSE", "imse_approx", "time", "smoothing_time", "solving_time"]
    res = {key: [None] * N_SIM for key in keys}
    for i in range(N_SIM):
        print(f"centered_{CENTERED} constraints_{name} knots_{KNOTS} N_{N} Simulacion_{i}")
        out = SOFR_basis(
            X_se[(i * N):(N * (i + 1)), 0:M1], t, y[i, :].reshape(1, N), Beta_real,
            DEGREE, KNOTS, G, CENTERED, int_constraints, ALPHA_CONSTRAINTS,
        )
        for key, value in zip(keys, out):
            res[key][i] = value
        print("\n")
    return res


def summarize(res, t, Beta_real, int_constraints, basename):
    """Write the metrics report and return the summary statistics."""
    beta_true = np.array(Beta_real)[:, 0]
    MSE_avg, MSE_std = mean_std(res["MSE"])
    IMSE_avg, IMSE_std = mean_std(res["imse_approx"])
    Beta_media, IntSquBias, IVar = bias_variance(t, beta_true, res["Beta_est"])
    summary = {
        "MSE_avg": MSE_avg, "IMSE_avg": IMSE_avg, "MSE_std": MSE_std, "IMSE_std": IMSE_std,
        "IntSquBias": IntSquBias, "IVar": IVar,
        "time_avg": np.mean(res["time"]),
        "smoothing_time_avg": np.mean(res["smoothing_time"]),
        "solving_time_avg": np.mean(res["solving_time"]),
        "Beta_media": Beta_media,
    }
    write_report(
        OUTPUT / f"{basename}.txt",
        title=("RESULTS int_constraints", int_constraints),
        raw=[
            ("MSE", res["MSE"]),
            ("IMSE", res["imse_approx"]),
            ("Smoothing Time", res["smoothing_time"]),
            ("Solving Time", res["solving_time"]),
            ("Total Time", res["time"]),
        ],
        averaged=[
            ("MSE_avg", MSE_avg),
            ("MSE_std", MSE_std),
            ("IMSE_avg", IMSE_avg),
            ("IMSE_std", IMSE_std),
            ("ISB", IntSquBias),
            ("IVar", IVar),
            ("Smoothing Time", summary["smoothing_time_avg"]),
            ("Solving Time", summary["solving_time_avg"]),
            ("Total Time", summary["time_avg"]),
        ],
    )
    return summary


def main():
    for N in N_VALUES:
        X_se, y, t, Beta_real = load_data(N)
        beta_true = np.array(Beta_real)[:, 0]
        for name, int_constraints in CONSTRAINTS.items():
            basename = f"X_Scenario{SCENARIO}_N_{N}_m_{M1}_int_constraints_{name}_centered_{CENTERED}_knots_{KNOTS}"
            print("\n")
            res = run_simulations(X_se, y, t, Beta_real, N, name, int_constraints)
            res["Beta_est"] = np.array(res["Beta_est"])
            summary = summarize(res, t, Beta_real, int_constraints, basename)

            # Plots: mean estimate with 95% band, and some individual estimates
            Beta_low, Beta_upp = plot_band(t, beta_true, res["Beta_est"], YLIM, OUTPUT / f"{basename}.png")
            plot_some(t, beta_true, res["Beta_est"], YLIM, OUTPUT / f"{basename}_somebetas.png")

            save_shelf(OUTPUT / f"{basename}.dat", {
                **res, **summary,
                "Beta_upp": Beta_upp, "Beta_low": Beta_low,
                "Scenario": SCENARIO, "N": N, "m1": M1,
                "int_constraints": int_constraints, "alpha_constraints": ALPHA_CONSTRAINTS,
            })


if __name__ == "__main__":
    main()
